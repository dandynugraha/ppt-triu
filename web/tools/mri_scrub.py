"""Frames for the title-slide MRI scrub: the same patient (TCGA-02-0059), the same crop and rendering as the PPTX
title tiles (ppt last/tools/render_mri.py: radiological axial view, per-slice 0.5–99.5 % window, transparent
background), for slices z = 95, 93, …, 83 of T1, T1-Gd, T2, FLAIR. Real data, skull-stripped, axial only.
usage: python web/tools/mri_scrub.py [input/mri] [web]"""
import glob, json, os, sys
import numpy as np, nibabel as nib
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else 'input/mri'
WEB = sys.argv[2] if len(sys.argv) > 2 else 'web'
OUT = os.path.join(WEB, 'img', 'mri', 'scrub'); os.makedirs(OUT, exist_ok=True)
SEQ = ['t1', 't1Gd', 't2', 'flair']
Z0, ZS = 95, list(range(95, 82, -2))
SCALE = 2
orient = np.rot90          # same as render_mri.py


def load(s):
    return np.asarray(nib.load(glob.glob(os.path.join(SRC, f'*_{s}.nii.gz'))[0]).dataobj).astype(np.float32)


vols = {s: load(s) for s in SEQ}
m0 = orient(vols['t1Gd'][:, :, Z0] > 0)
for s in SEQ:
    m0 |= orient(vols[s][:, :, Z0] > 0)
ys, xs = np.where(m0)
pad = 4
y0, y1, x0, x1 = max(ys.min() - pad, 0), ys.max() + pad, max(xs.min() - pad, 0), xs.max() + pad
for z in ZS:
    mask = orient(vols['t1Gd'][:, :, z] > 0)
    for s in SEQ:
        mask |= orient(vols[s][:, :, z] > 0)
    for s in SEQ:
        sl = orient(vols[s][:, :, z])
        v = sl[mask]
        lo, hi = np.percentile(v, 0.5), np.percentile(v, 99.5)
        g = np.clip((sl - lo) / (hi - lo), 0, 1) * 255
        rgba = np.dstack([g, g, g, mask * 255]).astype(np.uint8)[y0:y1, x0:x1]
        im = Image.fromarray(rgba, 'RGBA')
        im.resize((im.width * SCALE, im.height * SCALE), Image.LANCZOS).save(os.path.join(OUT, f'{s}_z{z:03d}.png'), optimize=True)
with open(os.path.join(WEB, 'data', 'mri_scrub.js'), 'w') as f:
    f.write('/* generated by web/tools/mri_scrub.py — TCGA-02-0059, BraTS-TCGA-GBM (CC BY 3.0) */\nwindow.MRI_SCRUB = ' +
            json.dumps({'case': 'TCGA-02-0059', 'z': ZS, 'crop': [int(y0), int(y1), int(x0), int(x1)]}) + ';\n')
print('frames', len(ZS) * len(SEQ), 'crop', (y0, y1, x0, x1), 'size', ((x1 - x0) * SCALE, (y1 - y0) * SCALE))
